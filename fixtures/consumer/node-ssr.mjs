import { Notice } from "@cosborn2/ui/notice";
import { Toast, ToastViewport } from "@cosborn2/ui/toast";
import { ActionsMenu } from "@cosborn2/ui/actions-menu";
import assert from "node:assert/strict";
import { createElement } from "react";
import { renderToString } from "react-dom/server";
import { Button } from "@cosborn2/ui/button";
import { Input } from "@cosborn2/ui/input";
import { Select } from "@cosborn2/ui/select";
import { Modal } from "@cosborn2/ui/modal";
import { SettingsCard } from "@cosborn2/ui/settings";

assert.equal(typeof window, "undefined");
assert.equal(typeof document, "undefined");
assert.match(renderToString(createElement(Button, null, "Node SSR button")), /Node SSR button/);
assert.match(renderToString(createElement(Input, { label: "Name", error: "Required" })), /aria-invalid="true"/);
assert.match(renderToString(createElement(Select, { label: "Choice" }, createElement("option", null, "One"))), /<select/);
assert.match(renderToString(createElement(SettingsCard, null, "Node settings")), /Node settings/);
const open = renderToString(createElement(Modal, { open: true, onOpenChange() {}, title: "Initially open" }, "Portal content"));
assert.doesNotMatch(open, /role="dialog"/);
assert.doesNotMatch(open, /Portal content/);
assert.match(renderToString(createElement(Notice, null, "Node notice")), /Node notice/);
assert.match(renderToString(createElement(ToastViewport, null, createElement(Toast, { message: "Node toast" }))), /Node toast/);
const menu = renderToString(createElement(ActionsMenu, { items: [{ label: "Archive", onClick() {} }], defaultOpen: true }));
assert.doesNotMatch(menu, /role="menu"/);
assert.match(menu, /aria-haspopup="menu"/);
console.log("Node SSR imports and rendering passed; initially open portal waits for mount.");
